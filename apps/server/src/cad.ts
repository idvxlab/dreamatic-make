import modeling from "@jscad/modeling";
import { serialize } from "@jscad/stl-serializer";
import { InputError, record } from "@harness/core";
const {
  primitives,
  booleans,
  transforms,
  geometries,
  measurements,
  modifiers,
} = modeling;
/** A bounded declarative model, not executable model-authored code. Units are millimeters. */
export function generateCAD(input: unknown) {
  const recipe = record(input),
    parameters = record(recipe.parameters ?? {});
  if (Object.keys(parameters).length > 80)
    throw new InputError("At most 80 CAD parameters");
  for (const [name, value] of Object.entries(parameters))
    if (
      !/^[a-zA-Z][a-zA-Z0-9_]*$/.test(name) ||
      typeof value !== "number" ||
      !Number.isFinite(value) ||
      Math.abs(value) > 10000
    )
      throw new InputError(`Invalid CAD parameter: ${name}`);
  let nodes = 0;
  const number = (value: unknown, positive = false): number => {
    const resolved =
      typeof value === "string" && value.startsWith("$")
        ? parameters[value.slice(1)]
        : value;
    if (
      typeof resolved !== "number" ||
      !Number.isFinite(resolved) ||
      Math.abs(resolved) > 10000 ||
      (positive && resolved <= 0)
    )
      throw new InputError("Invalid geometry dimension");
    return resolved;
  };
  const vector = (value: unknown, positive = false): number[] => {
    if (!Array.isArray(value) || value.length !== 3)
      throw new InputError("Expected a three-dimensional vector");
    return value.map((item) => number(item, positive));
  };
  const compile = (
    value: unknown,
    depth = 0,
  ): { geometry: unknown; scad: string } => {
    if (++nodes > 100 || depth > 9)
      throw new InputError("CAD recipe complexity exceeded");
    const node = record(value),
      op = node.op;
    if (op === "box") {
      const size = vector(node.size, true);
      return {
        geometry: primitives.cuboid({ size }),
        scad: `cube(${JSON.stringify(size)}, center=true);`,
      };
    }
    if (op === "cylinder") {
      const radius = number(node.radius, true),
        height = number(node.height, true),
        segments =
          node.segments === undefined ? 32 : number(node.segments, true);
      if (!Number.isInteger(segments) || segments < 12 || segments > 64)
        throw new InputError("Cylinder segments must be 12–64");
      return {
        geometry: primitives.cylinder({ radius, height, segments }),
        scad: `cylinder(h=${height}, r=${radius}, center=true, $fn=${segments});`,
      };
    }
    if (op === "translate" || op === "rotate") {
      const v = vector(node.value),
        child = compile(node.child, depth + 1);
      return {
        geometry:
          op === "translate"
            ? transforms.translate(v, child.geometry)
            : transforms.rotate(
                v.map((angle) => (angle * Math.PI) / 180),
                child.geometry,
              ),
        scad: `${op}(${JSON.stringify(v)}) { ${child.scad} }`,
      };
    }
    if (op === "union" || op === "subtract" || op === "intersect") {
      if (
        !Array.isArray(node.children) ||
        node.children.length < 2 ||
        node.children.length > 12
      )
        throw new InputError("Boolean operation needs 2–12 children");
      const children = node.children.map((child) => compile(child, depth + 1));
      return {
        geometry: booleans[op](...children.map((child) => child.geometry)),
        scad: `${op === "subtract" ? "difference" : op === "intersect" ? "intersection" : "union"}() {\n${children.map((child) => child.scad).join("\n")}\n}`,
      };
    }
    throw new InputError(`Unsupported CAD operation: ${String(op)}`);
  };
  const compiled = compile(recipe.geometry);
  const geometry = modifiers.generalize(
      { snap: true, triangulate: true },
      compiled.geometry,
    ),
    scad = compiled.scad;
  geometries.geom3.validate(geometry);
  const volume = measurements.measureVolume(geometry),
    bounds = measurements.measureBoundingBox(geometry);
  if (!Number.isFinite(volume) || volume <= 0.000001)
    throw new InputError("Geometry is empty or has invalid volume");
  const stl = serialize({ binary: false }, geometry).join("");
  return {
    stl,
    scad: `// Generated by dreamatic-make. Units: mm. Editable recipe is the sibling JSON file.\n${scad}\n`,
    recipe,
    report: {
      units: "mm",
      volumeMm3: volume,
      boundsMm: bounds,
      validation:
        "CSG geometry validation and positive volume only. Not a printability, tolerance, assembly or physical test.",
    },
  };
}
